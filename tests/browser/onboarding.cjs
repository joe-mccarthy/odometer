/* Disposable empty server at 127.0.0.1:8876; same tooling as dashboard.cjs. */
const { chromium } = require('playwright');
const AxeBuilder = require('@axe-core/playwright').default;
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ viewport: { width: 320, height: 800 } });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  const ready = () => page.locator('#status').filter({ hasText: /Up to date|Saved|Ready to record/ }).waitFor();
  const reload = async () => { await page.reload(); await ready(); };
  const request = async (path, method = 'GET', body) => page.evaluate(async ({path, method, body}) => {
    const r = await fetch('/api' + path, { method, headers: {'Content-Type':'application/json', 'X-Odometer-Request':'1'}, body: body && JSON.stringify(body) });
    if (!r.ok) throw Error(await r.text());
    return r.json();
  }, {path, method, body});
  const scope = () => page.locator('#vehicle').inputValue();
  await page.goto('http://127.0.0.1:8876'); await ready();
  assert.equal((await request('/vehicles?include_inactive=true')).length, 0);
  assert.equal(await page.locator('#vehicle-form').isVisible(), true);
  assert.match(await page.locator('#creation').textContent(), /then record fuel or an expense/);
  const a = await request('/vehicles', 'POST', {registration:'ONBOARD A', initial_mileage:0});
  await reload(); assert.equal(await scope(), a.id);
  assert.equal(await page.locator('#records').isVisible(), true);
  assert.equal(await page.locator('#vehicle-form').isVisible(), false);
  await page.locator('#vehicle').selectOption(''); await ready();
  await page.locator('#refresh').click(); await ready(); assert.equal(await scope(), '');
  await page.locator('#inactive').check(); await ready(); assert.equal(await scope(), '');
  await page.locator('#add-vehicle').click();
  assert.equal(await page.locator(':focus').getAttribute('id'), 'vehicle-form-registration');
  await page.keyboard.press('Escape');
  assert.equal(await page.locator(':focus').getAttribute('id'), 'add-vehicle');
  await page.locator('#add-vehicle').click();
  await page.locator('#cancel-vehicle').click();
  assert.equal(await page.locator(':focus').getAttribute('id'), 'add-vehicle');
  await page.locator('#add-vehicle').click();
  await page.locator('#vehicle-form-registration').fill('ONBOARD B');
  await page.locator('#vehicle-form-initial_mileage').fill('10');
  assert.deepEqual((await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze()).violations, []);
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.locator('#vehicle-form button').click(); await ready();
  const b = (await request('/vehicles')).find(v => v.registration === 'ONBOARD B');
  assert.equal(await scope(), b.id);
  assert.equal(await page.locator(':focus').getAttribute('id'), 'context');
  await reload(); assert.equal(await scope(), ''); // multiple active
  await page.locator('#vehicle').selectOption(b.id); await ready();
  await page.locator('#refresh').click(); await ready(); assert.equal(await scope(), b.id);
  await request('/vehicles/'+a.id, 'PATCH', {status:'SOLD'});
  await request('/vehicles/'+b.id, 'PATCH', {status:'ARCHIVED'});
  await reload(); assert.equal(await scope(), '');
  assert.match(await page.locator('#vehicle-detail').textContent(), /No active vehicles/);
  assert.equal(await page.locator('#vehicle-form').isVisible(), false);
  await page.locator('#inactive').check(); await ready(); assert.equal(await scope(), '');
  await page.locator('#vehicle').selectOption(a.id); await ready();
  await page.locator('#inactive').uncheck(); await ready(); assert.equal(await scope(), '');
  assert.match(await page.locator('#status').textContent(), /no longer available/);
  assert.deepEqual((await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze()).violations, []);
  for (const v of [a,b]) await request('/vehicles/'+v.id, 'DELETE');
  await reload(); assert.equal(await page.locator('#vehicle-form').isVisible(), true);
  assert.deepEqual(errors, []);
  await browser.close();
  console.log('PASS criteria 10.1–10.5: zero/one/multiple, explicit scope, inactive-only, modal focus/cancel/create, 320px, axe');
})().catch(e => {console.error(e); process.exit(1);});
